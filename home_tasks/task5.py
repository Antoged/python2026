num1 = float(input("Введите первое число: "))
num2 = float(input("Введите второе число: "))

addition = num1 + num2
subtraction = num1 - num2
multiplication = num1 * num2
division = num1 / num2
floor_division = num1 // num2
remainder = num1 % num2
exponentiation = num1 ** num2

print("Сумма:", addition)
print("Разность:", subtraction)
print("Произведение:", multiplication)
print("Частное:", division)
print("Целочисленное деление:", floor_division)
print("Остаток от деления:", remainder)
print("Возведение в степень:", exponentiation)
